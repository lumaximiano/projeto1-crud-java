    private void configurarTabela() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
    }

    private void configurarEventos() {
        btnSalvar.addActionListener(e -> salvar());
        btnAtualizar.addActionListener(e -> atualizar());
        btnExcluir.addActionListener(e -> excluir());
        btnLimpar.addActionListener(e -> limparCampos());

        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && jTable1.getSelectedRow() != -1) {
                linhaSelecionada = jTable1.getSelectedRow();
                Cliente c = clientes.get(linhaSelecionada);
                preencherCampos(c);
            }
        });
    }

    private void salvar() {
        if (!validarCampos()) return;

        Cliente c = new Cliente(
                txtNome.getText().trim(),
                txtCpf.getText().trim(),
                txtEndereco.getText().trim(),
                txtNumero.getText().trim(),
                txtCidade.getText().trim(),
                txtEstado.getText().trim(),
                txtTel.getText().trim()
        );

        clientes.add(c);
        adicionarLinhaNaTabela(c);
        limparCampos();
    }

    private void atualizar() {
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma linha na tabela para atualizar.");
            return;
        }
        if (!validarCampos()) return;

        Cliente c = clientes.get(linhaSelecionada);
        c.setNome(txtNome.getText().trim());
        c.setCpf(txtCpf.getText().trim());
        c.setEndereco(txtEndereco.getText().trim());
        c.setNumero(txtNumero.getText().trim());
        c.setCidade(txtCidade.getText().trim());
        c.setEstado(txtEstado.getText().trim());
        c.setTelefone(txtTel.getText().trim());

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setValueAt(c.getNome(), linhaSelecionada, 0);
        model.setValueAt(c.getCpf(), linhaSelecionada, 1);
        model.setValueAt(c.getCidade(), linhaSelecionada, 2);
        model.setValueAt(c.getEstado(), linhaSelecionada, 3);

        limparCampos();
    }

    private void excluir() {
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma linha na tabela para excluir.");
            return;
        }

        clientes.remove(linhaSelecionada);
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.removeRow(linhaSelecionada);

        limparCampos();
    }

    private void limparCampos() {
        txtNome.setText("");
        txtCpf.setText("");
        txtEndereco.setText("");
        txtNumero.setText("");
        txtCidade.setText("");
        txtEstado.setText("");
        txtTel.setText("");
        linhaSelecionada = -1;
        jTable1.clearSelection();
    }

    private void preencherCampos(Cliente c) {
        txtNome.setText((String) c.getNome());
        txtCpf.setText((String) c.getCpf());
        txtEndereco.setText(c.getEndereco());
        txtNumero.setText(c.getNumero());
        txtCidade.setText((String) c.getCidade());
        txtEstado.setText((String) c.getEstado());
        txtTel.setText(c.getTelefone());
    }

    private void adicionarLinhaNaTabela(Cliente c) {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.addRow(new Object[]{c.getNome(), c.getCpf(), c.getCidade(), c.getEstado()});
    }

    private boolean validarCampos() {
        if (txtNome.getText().trim().isEmpty() || txtCpf.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nome e CPF são obrigatórios.");
            return false;
        }
        return true;
    }

